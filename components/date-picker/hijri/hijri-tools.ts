/** Hijri date parts. `month` is 1-indexed (1 = Muharram, 12 = Dhu al-Hijjah). */
export interface NzHijriDateParts {
  year: number;
  month: number;
  day: number;
}

/**
 * Overrides the length of a single Hijri month.
 *
 * Local moon sighting may differ from the tabular Umm al-Qura calendar. An override changes the
 * length of one month and shifts every following month by the same amount.
 */
