const MONTHS_IN_YEAR = 12;

/** Converts a Gregorian year/month/day (month is 1-indexed) to a Julian Day Number. */
function gregorianToJulianDay(year: number, month: number, day: number): number {
  const a = Math.floor((14 - month) / 12);
  const y = year + 4800 - a;
  const m = month + 12 * a - 3;
  return (
    day +
    Math.floor((153 * m + 2) / 5) +
    365 * y +
    Math.floor(y / 4) -
    Math.floor(y / 100) +
    Math.floor(y / 400) -
    32045
  );
}

/** Converts a Julian Day Number back to Gregorian parts (month is 1-indexed). */
function julianDayToGregorian(jd: number): NzHijriDateParts {
  const a = jd + 32044;
  const b = Math.floor((4 * a + 3) / 146097);
  const c = a - Math.floor((146097 * b) / 4);
  const d = Math.floor((4 * c + 3) / 1461);
  const e = c - Math.floor((1461 * d) / 4);
  const m = Math.floor((5 * e + 2) / 153);
  return {
    day: e - Math.floor((153 * m + 2) / 5) + 1,
    month: m + 3 - 12 * Math.floor(m / 10),
    year: 100 * b + d - 4800 + Math.floor(m / 10)
  };
}

/** Index of a Hijri month inside the lookup table, or `-1` when out of range. */
function monthIndex(year: number, month: number): number {
  const index = (year - NZ_HIJRI_MIN_YEAR) * MONTHS_IN_YEAR + (month - 1);
  return index >= 0 && index < UMM_AL_QURA_DATA.length ? index : -1;
}

let cachedKey = '';
let cachedTable: readonly number[] = UMM_AL_QURA_DATA;

/** Builds a cache key that changes whenever the effective set of overrides changes. */
function overridesKey(overrides: readonly NzHijriMonthOverride[]): string {
  return overrides.map(o => `${o.year}/${o.month}/${o.days}`).join(',');
}

/**
 * Builds a copy of the Umm al-Qura table with every override applied.
 *
 * An override changes the length of its month, which shifts the start of all following months by
 * the same delta. Multiple overrides compound. The result is memoized, since a single panel render
 * converts hundreds of dates.
 */
function correctedTable(overrides?: readonly NzHijriMonthOverride[]): readonly number[] {
  if (!overrides?.length) {
    return UMM_AL_QURA_DATA;
  }

  const key = overridesKey(overrides);
  if (key === cachedKey) {
    return cachedTable;
  }

  const sorted = overrides
    .filter(o => {
      const index = monthIndex(o.year, o.month);
      return index >= 0 && index < UMM_AL_QURA_DATA.length - 1;
    })
    .sort((a, b) => monthIndex(a.year, a.month) - monthIndex(b.year, b.month));

  const table = [...UMM_AL_QURA_DATA];
  let shift = 0;
  let lastIndex = -1;

  for (const override of sorted) {
    const index = monthIndex(override.year, override.month);
    // Everything up to and including the overridden month only carries the shift accumulated so far
    for (let i = lastIndex + 1; i <= index; i++) {
      table[i] += shift;
    }
    shift += override.days - (UMM_AL_QURA_DATA[index + 1] - UMM_AL_QURA_DATA[index]);
    lastIndex = index;
  }

  for (let i = lastIndex + 1; i < table.length; i++) {
    table[i] += shift;
  }

  cachedKey = key;
  cachedTable = table;
  return table;
}

/** Converts a native date to Hijri parts. */
export function gregorianToHijri(date: Date, overrides?: readonly NzHijriMonthOverride[]): NzHijriDateParts {
  const table = correctedTable(overrides);
  const jd = gregorianToJulianDay(date.getFullYear(), date.getMonth() + 1, date.getDate());
  // Clamp to the covered range instead of throwing, so an out-of-range date still renders
  if (jd < table[0]) {
    return { year: NZ_HIJRI_MIN_YEAR, month: 1, day: 1 };
  }

  let index = 0;
  while (index < table.length - 1 && table[index + 1] <= jd) {
    index++;
  }

  return {
    year: Math.floor(index / MONTHS_IN_YEAR) + NZ_HIJRI_MIN_YEAR,
    month: (index % MONTHS_IN_YEAR) + 1,
    day: jd - table[index] + 1
  };
}

/**
 * Converts Hijri parts to a native date at midnight.
 *
 * Out of range years are clamped and overflowing days roll into the following month, mirroring the
 * behaviour of `new Date(year, month, day)`.
 */
export function hijriToGregorian(hijri: NzHijriDateParts, overrides?: readonly NzHijriMonthOverride[]): Date {
  const table = correctedTable(overrides);
  // Normalize an out of bounds month into the neighbouring year, e.g. month 13 of 1446 is month 1 of 1447
  const monthsFromYearStart = hijri.month - 1;
  const year = hijri.year + Math.floor(monthsFromYearStart / MONTHS_IN_YEAR);
  const month = ((monthsFromYearStart % MONTHS_IN_YEAR) + MONTHS_IN_YEAR) % MONTHS_IN_YEAR;
  const index = monthIndex(Math.min(Math.max(year, NZ_HIJRI_MIN_YEAR), NZ_HIJRI_MAX_YEAR), month + 1);
  const { year: gy, month: gm, day: gd } = julianDayToGregorian(table[index] + hijri.day - 1);
  return new Date(gy, gm - 1, gd);
}

/** Returns the number of days (29 or 30) in the given Hijri month. */
export function getHijriMonthLength(year: number, month: number, overrides?: readonly NzHijriMonthOverride[]): number {
  const table = correctedTable(overrides);
  const index = monthIndex(year, month);
  return index < 0 || index >= table.length - 1 ? 30 : table[index + 1] - table[index];
}

/** Returns the number of days in the given Hijri year. */
export function getHijriYearLength(year: number, overrides?: readonly NzHijriMonthOverride[]): number {
  let days = 0;
  for (let month = 1; month <= MONTHS_IN_YEAR; month++) {
    days += getHijriMonthLength(year, month, overrides);
  }
  return days;
}
